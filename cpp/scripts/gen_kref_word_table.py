"""Generate cpp/src/kref_word_table.inc, the Unicode word-class table of the kref parser.

The kumiho-db kernel reads a kref segment with the Rust regex crate's ``\\w``:
Alphabetic | Mark | Decimal_Number | Connector_Punctuation | Join_Control. The C++
SDK has no Unicode library, so ``src/kref_parts.cpp`` looks code points up in the
sorted range table this script writes. The class is built the way the shared
corpus generator (spec/kref/tools/gen_vectors.py) builds it, from the Unicode
general categories L*, M*, Nd, Nl and Pc plus U+200C/U+200D, with the one set of
Other_Alphabetic code points that are not letters or marks (the circled and
squared Latin letters) added so the table matches Alphabetic.

Run from the repository root:

    python cpp/scripts/gen_kref_word_table.py

Only code points >= U+0080 are listed; ASCII is decided in code.
"""

import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src" / "kref_word_table.inc"

# Other_Alphabetic code points whose general category is So (PropList.txt).
OTHER_ALPHABETIC_SYMBOLS = [
    (0x24B6, 0x24E9),
    (0x1F130, 0x1F149),
    (0x1F150, 0x1F169),
    (0x1F170, 0x1F189),
]


def is_word(cp: int) -> bool:
    category = unicodedata.category(chr(cp))
    return (
        category[0] in "LM"
        or category in ("Nd", "Nl", "Pc")
        or cp in (0x200C, 0x200D)
        or any(lo <= cp <= hi for lo, hi in OTHER_ALPHABETIC_SYMBOLS)
    )


def ranges():
    start = None
    for cp in range(0x80, 0x110000):
        if is_word(cp):
            if start is None:
                start = cp
        elif start is not None:
            yield start, cp - 1
            start = None
    if start is not None:
        yield start, 0x10FFFF


def main() -> None:
    table = list(ranges())
    lines = [
        "// Generated by cpp/scripts/gen_kref_word_table.py - do not edit.",
        f"// Unicode {unicodedata.unidata_version}: the kref word class for code points >= U+0080.",
        "// Sorted, non-overlapping, inclusive [first, last] ranges.",
    ]
    lines += [f"{{0x{lo:X}, 0x{hi:X}}}," for lo, hi in table]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(table)} ranges to {OUT}")


if __name__ == "__main__":
    main()
